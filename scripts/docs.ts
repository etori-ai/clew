/** Generate integrator references from real contracts and manifests; --check never writes files. */
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  protocolSchema,
  PROTOCOL_VERSION,
  ManifestCapabilitySchema,
  ManifestAreaSchema,
} from '../packages/connectors/src/protocol';
import { parseManifest } from '../packages/connectors/src/remote';
import { manifest as hello } from '../connectors/hello/connector.mjs';
import { manifest as telefonbok } from '../connectors/telefonbok/connector.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
const json = (value: unknown) => JSON.stringify(value, null, 2) + '\n';
const read = (path: string) => readFileSync(resolve(root, path), 'utf8');
const generated = new Map<string, string>();
const table = (text: string) => text.replaceAll('|', '\\|').replaceAll('\n', ' ');
function files(directory: string): string[] {
  return readdirSync(resolve(root, directory), { withFileTypes: true })
    .flatMap(entry => {
      const path = `${directory}/${entry.name}`;
      return entry.isDirectory() ? files(path) : [path];
    })
    .sort();
}
function metadata(source: string, field: string) {
  return (
    source
      .replaceAll('**', '')
      .match(new RegExp(`(?:^| · )${field}:\\s*([^\\n·]+)`, 'm'))?.[1]
      ?.trim() ?? ''
  );
}
const titleOf = (source: string) => source.match(/^# (.+)$/m)?.[1] ?? '';
const decisions = files('docs/decisions')
  .filter(path => /\/D\d+-.+\.md$/.test(path))
  .map(path => {
    const source = read(path),
      name = path.split('/').at(-1)!;
    const record = {
      key: name.slice(0, -3),
      number: Number(name.match(/^D(\d+)/)![1]),
      path,
      title: titleOf(source),
      status: metadata(source, 'Status'),
      date: metadata(source, 'Date'),
      area: metadata(source, 'Area'),
    };
    if (!record.title || !record.status || !record.date || !record.area)
      throw new Error(`Missing decision metadata: ${path}`);
    return record;
  });
const duplicates = [
  ...new Set(
    decisions.filter(a => decisions.some(b => a.number === b.number && a.path !== b.path)).map(d => `D${d.number}`),
  ),
];
const reviews = files('docs/reviews')
  .filter(path => /\/\d{4}-\d{2}-\d{2}-.+\.md$/.test(path))
  .map(path => ({ path, title: titleOf(read(path)) }));
const manifests = [parseManifest(hello, 'hello'), parseManifest(telefonbok, 'telefonbok')];
const banner = '<!-- Generated by scripts/docs.ts. Edit the source, then run bun run docs:generate. -->\n\n';
generated.set('docs/protocol/connector-protocol.schema.json', json(protocolSchema()));
for (const manifest of manifests) generated.set(`docs/generated/${manifest.id}.manifest.json`, json(manifest));

function shape(schema: Record<string, any>): string {
  if ('const' in schema) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((v: unknown) => JSON.stringify(v)).join(' / ');
  if (schema.anyOf || schema.oneOf) return (schema.anyOf ?? schema.oneOf).map(shape).join(' / ');
  if (schema.type === 'array') return `array of ${shape(schema.items ?? {})}`;
  return schema.type ?? 'JSON value';
}
const protocol = protocolSchema();
const documentedShapes: Record<string, any> = {
  ...protocol.$defs,
  ManifestCapability: ManifestCapabilitySchema,
  ManifestArea: ManifestAreaSchema,
};
const fieldTables = [
  'ConnectorManifest',
  'ManifestCapability',
  'ManifestArea',
  'Actor',
  'CallRequest',
  'ThreadDraft',
  'ExecuteResult',
  'CallbackRequest',
].map(name => {
  const schema = documentedShapes[name];
  return (
    `## ${name}\n\n| Field | Required | Shape | Description |\n|---|---|---|---|\n` +
    Object.entries(schema.properties as Record<string, any>)
      .map(
        ([key, value]) =>
          `| \`${key}\` | ${schema.required?.includes(key) ? 'yes' : 'no'} | ${table(shape(value))} | ${table(value.description ?? '')} |`,
      )
      .join('\n')
  );
});
generated.set(
  'docs/generated/README.md',
  banner +
    '# Generated connector reference\n\n' +
    `Protocol version: **${PROTOCOL_VERSION}**. Generated from [protocol.ts](../../packages/connectors/src/protocol.ts), its imported contracts and the real connector manifest exports. ` +
    'The tables are field summaries; use the [JSON Schema bundle](../protocol/connector-protocol.schema.json) for nested fields, constraints, required properties and unions. Schema validation does not replace [behavioral validation](../guides/testing-and-deployment.md).\n\n' +
    '## Complete runnable examples\n\n' +
    manifests
      .map(
        m =>
          `- [${m.id} manifest](${m.id}.manifest.json), from [connector.mjs](../../connectors/${m.id}/connector.mjs): ${m.capabilities.length} capabilities; ${m.scan ? 'scan enabled' : 'no scan'}.`,
      )
      .join('\n') +
    '\n\nThese JSON files are complete, generated inputs, not abbreviated pseudocode. They contain no credentials. The [signed walkthrough](../../scripts/docs-smoke.ts) runs the phone book fixture; the [quickstart](../guides/creating-a-connector.md) explains how to adapt it.\n\n' +
    fieldTables.join('\n\n') +
    '\n',
);

generated.set(
  'docs/decisions/README.md',
  banner +
    '# Decision log\n\n' +
    'These records preserve why choices were made. The status below is copied from each original record, not inferred from code. An accepted decision may be partly implemented, and an older status may lag delivery. Use [implementation status](../reference/status.md) and the [current protocol](../reference/connector-protocol.md) when building a connector.\n\n' +
    `Historical numbering collisions: **${duplicates.join(', ')}** each identify more than one file. The full filename is the unique key. Keep existing filenames and links; never interpret a bare collided number without its title. No decisions were renumbered or accepted by this index.\n\n` +
    '| Record | Area | Date | Recorded status |\n|---|---|---|---|\n' +
    decisions
      .map(d => `| [${table(d.title)}](${d.path.split('/').at(-1)}) | ${d.area} | ${d.date} | ${table(d.status)} |`)
      .join('\n') +
    '\n\n## Add a decision\n\n' +
    `Use [TEMPLATE.md](TEMPLATE.md) and a new unused number (currently D${Math.max(...decisions.map(d => d.number)) + 1}). Include status, date, area, decision, rationale and what it replaces. ` +
    'Preserve earlier decision bodies; record supersession explicitly. Refer to the full filename when a number is ambiguous. Update the implementation-status guide when delivery changes, add a session note to [HANDOVER.md](../../HANDOVER.md), and run `bun run docs:generate` followed by `bun run docs:check`. The generated context map includes every record.\n',
);
generated.set(
  'docs/reviews/README.md',
  banner +
    '# Reviews and explorations\n\n' +
    'Dated evidence, design explorations and recommendations. They are historical context, not the current integration contract or instructions to implement every recommendation. Later outcomes belong in an Outcome section or a new review; decisions remain in the [decision log](../decisions/README.md). Start integration work with the [documentation home](../README.md).\n\n' +
    reviews.map(r => `- [${r.title}](${r.path.split('/').at(-1)})`).join('\n') +
    '\n',
);

const canonical = {
  protocol: 'packages/connectors/src/protocol.ts',
  contracts: 'packages/contracts/src/index.ts',
  transport: 'packages/connectors/src/remote.ts',
  registry: 'packages/connectors/src/index.ts',
  viewValidation: 'packages/connectors/src/views.ts',
  signingAuthority: 'apps/server/src/connectors/authority.ts',
  standaloneVerifier: 'connectors/hello/verification.mjs',
  callbacks: 'apps/server/src/routes/connectors.ts',
  conformance: 'packages/connectors/src/check.ts',
  executableWalkthrough: 'scripts/docs-smoke.ts',
  supportStatus: 'docs/reference/status.md',
};
const entrypoints = [
  'docs/overview.md',
  'docs/guides/creating-a-connector.md',
  'docs/reference/status.md',
  'docs/reference/connector-protocol.md',
  'docs/guides/authorization.md',
];
const docPaths = [
  ...new Set([
    'README.md',
    'CLAUDE.md',
    'HANDOVER.md',
    'llms.txt',
    ...files('docs'),
    ...files('connectors').filter(p => p.endsWith('.md')),
    ...generated.keys(),
  ]),
]
  .filter(p => p.endsWith('.md') || p === 'llms.txt')
  .sort();
const category = (path: string) =>
  path === 'HANDOVER.md'
    ? 'session-history'
    : path === 'CLAUDE.md'
      ? 'repository-instructions'
      : path.startsWith('docs/decisions/D')
        ? 'decision-history'
        : path.startsWith('docs/reviews/')
          ? 'review-history'
          : path.startsWith('docs/architecture/')
            ? 'maintainer-design'
            : path.startsWith('docs/maintainers/')
              ? 'maintainer-guide'
              : path.startsWith('docs/generated/')
                ? 'generated-reference'
                : 'integrator-guide';
generated.set(
  'docs/context.json',
  json({
    formatVersion: 1,
    generatedBy: 'scripts/docs.ts',
    pathBase: 'repository-root',
    protocolVersion: PROTOCOL_VERSION,
    authorityOrder: [
      'implementation-and-behavioral-tests',
      'generated-contracts-and-examples',
      'current-guides',
      'decision-intent',
      'historical-reviews-and-session-notes',
    ],
    entrypoints,
    canonical,
    commands: {
      generate: 'bun run docs:generate',
      check: 'bun run docs:check',
      smoke: 'bun run docs:smoke',
      hostPrefix: 'docker exec -w /workspace clew-app-1',
    },
    examples: manifests.map(m => ({
      id: m.id,
      source: `connectors/${m.id}/connector.mjs`,
      manifest: `docs/generated/${m.id}.manifest.json`,
      capabilities: m.capabilities.map(c => c.name),
    })),
    duplicateDecisionNumbers: duplicates,
    decisions,
    documents: docPaths.map(path => {
      const source = generated.get(path) ?? read(path);
      return {
        path,
        title: titleOf(source),
        category: category(path),
        headings: [...source.matchAll(/^## (.+)$/gm)].map(m => m[1]),
      };
    }),
  }),
);

const failures: string[] = [];
for (const [path, content] of generated) {
  if (check) {
    if (!existsSync(resolve(root, path)) || read(path) !== content)
      failures.push(`Generated file is stale: ${path}; run bun run docs:generate`);
  } else {
    mkdirSync(dirname(resolve(root, path)), { recursive: true });
    writeFileSync(resolve(root, path), content);
  }
}

/** Validate repository-relative Markdown links, including heading fragments; never fetch remote URLs. */
const withoutFences = (text: string) => text.replace(/^(`{3,}|~{3,})[^\n]*\n[\s\S]*?^\1[^\n]*$/gm, '');
function headingIds(source: string) {
  const counts = new Map<string, number>();
  return [...withoutFences(source).matchAll(/^#{1,6}\s+(.+)$/gm)].map(match => {
    const slug = match[1]!
      .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
      .replace(/<[^>]*>/g, '')
      .toLowerCase()
      .replace(/[^\p{L}\p{N}\s_-]/gu, '')
      .replace(/\s/g, '-');
    const n = counts.get(slug) ?? 0;
    counts.set(slug, n + 1);
    return n ? `${slug}-${n}` : slug;
  });
}
for (const path of docPaths) {
  const source = withoutFences(generated.get(path) ?? read(path));
  for (const match of source.matchAll(/\[[^\]\n]*\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g)) {
    const href = match[1]!.replace(/^<|>$/g, '');
    if (/^[a-z][a-z0-9+.-]*:/i.test(href) || href.startsWith('//')) continue;
    const [target, fragment] = href.split('#');
    let destination: string;
    try {
      destination = target
        ? resolve(dirname(resolve(root, path)), decodeURIComponent(target.split('?')[0]!))
        : resolve(root, path);
    } catch {
      failures.push(`${path}: malformed link ${href}`);
      continue;
    }
    const local = relative(root, destination).split(sep).join('/');
    if (local.startsWith('../') || (!generated.has(local) && !existsSync(destination))) {
      failures.push(`${path}: missing local link ${href}`);
      continue;
    }
    if (fragment && local.endsWith('.md') && (generated.has(local) || statSync(destination).isFile())) {
      if (!headingIds(generated.get(local) ?? read(local)).includes(decodeURIComponent(fragment)))
        failures.push(`${path}: missing heading ${href}`);
    }
  }
}
for (const path of [...Object.values(canonical), ...entrypoints])
  if (!existsSync(resolve(root, path))) failures.push(`Missing canonical source: ${path}`);
if (failures.length) {
  for (const failure of failures) console.error(failure);
  process.exit(1);
}
console.log(
  `Documentation ${check ? 'check' : 'generation'} passed: ${generated.size} generated files, ${decisions.length} decisions, ${docPaths.length} documents; local links checked.`,
);
