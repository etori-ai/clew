/** Validate repository-relative Markdown links, including heading fragments; never fetch remote URLs. */
const withoutFences = (text: string) => text.replace(/^(`{3,}|~{3,})[^\n]*\n[\s\S]*?^\1[^\n]*$/gm, '');
function headingIds(source: string) {
  const counts = new Map<string, number>();
  return [...withoutFences(source).matchAll(/^#{1,6}\s+(.+)$/gm)].map(match => {
    const slug = match[1]!
      .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
      .replace(/<[^>]*>/g, '')
      .toLowerCase()
      .replace(/[^\p{L}\p{N}\s_-]/gu, '')
      .replace(/\s/g, '-');
    const n = counts.get(slug) ?? 0;
    counts.set(slug, n + 1);
    return n ? `${slug}-${n}` : slug;
  });
}
for (const path of docPaths) {
  const source = withoutFences(generated.get(path) ?? read(path));
  for (const match of source.matchAll(/\[[^\]\n]*\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g)) {
    const href = match[1]!.replace(/^<|>$/g, '');
    if (/^[a-z][a-z0-9+.-]*:/i.test(href) || href.startsWith('//')) continue;
    const [target, fragment] = href.split('#');
    let destination: string;
    try {
      destination = target
        ? resolve(dirname(resolve(root, path)), decodeURIComponent(target.split('?')[0]!))
        : resolve(root, path);
    } catch {
      failures.push(`${path}: malformed link ${href}`);
      continue;
    }
    const local = relative(root, destination).split(sep).join('/');
    if (local.startsWith('../') || (!generated.has(local) && !existsSync(destination))) {
      failures.push(`${path}: missing local link ${href}`);
      continue;
    }
    if (fragment && local.endsWith('.md') && (generated.has(local) || statSync(destination).isFile())) {
      if (!headingIds(generated.get(local) ?? read(local)).includes(decodeURIComponent(fragment)))
        failures.push(`${path}: missing heading ${href}`);
    }
  }
}
